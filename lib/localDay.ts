/**
 * Сегодняшняя дата по местному времени, «ГГГГ-ММ-ДД».
 *
 * `new Date().toISOString().slice(0, 10)` — дата по UTC. В Казахстане это
 * вчера с полуночи до пяти утра: смену, записанную в половине первого
 * ночи, форма подставляла вчерашним числом, новая расценка ложилась на
 * вчерашние смены, а срок согласования «истекал» на день раньше. Ловило
 * уже трижды — отсюда отдельная функция вместо той строки.
 */
export function localDay(d: Date = new Date()): string {
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}
