export const DICT_KEYS = Object.keys(DICT);

/**
 * Перевод.
 *
 * Ключа нет в словаре — возвращаем сам ключ. Он и есть русская фраза,
 * так что не переведённое место выглядит непереведённым, а не сломанным.
 */
export function translate(key: string, lang: Lang): string {
  if (lang === 'ru') return DICT[key]?.ru ?? key;
  const pair = DICT[key];
  if (!pair) return key;
  return pair.kk.trim() || pair.ru;
}

/**
 * Чего ещё нет на втором языке.
 *
 * Пустой перевод — не ошибка, а «ещё не сверили». Но знать, сколько их,
 * нужно до того, как язык предложат людям.
 */
export function missing(lang: Lang, overrides: Record<string, string> = {}): string[] {
  if (lang === 'ru') return [];
  return DICT_KEYS.filter((k) => !(overrides[k]?.trim() || DICT[k][lang].trim()));
}

/** Доля переведённого — её и показываем рядом с переключателем. */
export function coverage(lang: Lang, overrides: Record<string, string> = {}): number {
  if (DICT_KEYS.length === 0) return 1;
  return 1 - missing(lang, overrides).length / DICT_KEYS.length;
}

// ── Настройка устройства ─────────────────────────────────────────────────

const KEY = 'optiq-lang';
const TERMS_KEY = 'optiq-lang-terms';

/**
 * По умолчанию русский.
 *
 * Не потому, что он главнее, а потому, что на нём сейчас весь журнал и
 * вся переписка со стройкой. Переключить — одно нажатие; получить
 * наполовину чужой интерфейс, ничего не нажимая, — неприятная
 * неожиданность.
 */
export function loadLang(): Lang {
  if (typeof window === 'undefined') return 'ru';
  try {
    return window.localStorage.getItem(KEY) === 'kk' ? 'kk' : 'ru';
  } catch {
    return 'ru';
  }
}

export function saveLang(v: Lang): void {
  if (typeof window === 'undefined') return;
  try { window.localStorage.setItem(KEY, v); } catch { /* приватный режим */ }
}

/** Свои переводы: что поправили руками, то и стоит в интерфейсе. */
export function loadLangTerms(): Record<string, string> {
  if (typeof window === 'undefined') return {};
  try {
    const raw = window.localStorage.getItem(TERMS_KEY);
    const v = raw ? JSON.parse(raw) : null;
    if (!v || typeof v !== 'object' || Array.isArray(v)) return {};
    const out: Record<string, string> = {};
    for (const [k, val] of Object.entries(v)) {
      if (typeof val === 'string') out[k] = val;
    }
    return out;
  } catch {
    return {};
  }
}

export function saveLangTerms(v: Record<string, string>): void {
  if (typeof window === 'undefined') return;
  try { window.localStorage.setItem(TERMS_KEY, JSON.stringify(v)); } catch { /* приватный режим */ }
}

/**
 * Готовая переводилка со своими правками.
 *
 * Её и раздаём по экранам: компонент не должен знать ни про словарь, ни
 * про то, где лежат правки.
 */
export function makeT(lang: Lang, overrides: Record<string, string> = {}) {
  return (key: string): string => {
    if (lang === 'ru') return DICT[key]?.ru ?? key;
    const own = overrides[key]?.trim();
    if (own) return own;
    return translate(key, lang);
  };
}
