import { describe, it, expect } from 'vitest';
import { parseTabular } from './CsvImporter';

/**
 * Таблица, вставленная из Excel или присланная файлом.
 *
 * Её делает человек в своей привычке: где-то точка с запятой, где-то
 * табуляция, координаты то в двух колонках, то одной строкой, десятичная
 * часть то через точку, то через запятую. Понять надо всё — переписывать
 * тысячу строк руками никто не станет.
 */

describe('разделители', () => {
  const rows = (text: string) => parseTabular(text);

  it('точка с запятой — как отдаёт русский Excel', () => {
    expect(rows('52.09;69.12;Школа\n52.10;69.13;ФАП')).toHaveLength(2);
  });

  it('табуляция — как вставляется из буфера', () => {
    expect(rows('52.09\t69.12\tШкола')).toHaveLength(1);
  });

  it('запятая — как в обычном CSV', () => {
    expect(rows('52.09,69.12,Школа')).toHaveLength(1);
  });
});

describe('координаты в разных видах', () => {
  it('двумя колонками', () => {
    const [s] = parseTabular('52.091435;69.123456;Школа');
    expect(s.lat).toBeCloseTo(52.091435, 6);
    expect(s.lon).toBeCloseTo(69.123456, 6);
  });

  it('одной строкой в первой колонке', () => {
    const [s] = parseTabular('52.091435, 69.123456\tШкола');
    expect(s.lat).toBeCloseTo(52.091435, 6);
    expect(s.desc).toBe('Школа');
  });

  it('десятичная запятая — так пишет русский Excel', () => {
    const [s] = parseTabular('52,091435;69,123456;Школа');
    expect(s.lat).toBeCloseTo(52.091435, 6);
    expect(s.lon).toBeCloseTo(69.123456, 6);
  });
});

describe('шапка таблицы', () => {
  it('шапку не принимает за точку', () => {
    const out = parseTabular('Широта;Долгота;Название\n52.09;69.12;Школа');
    expect(out).toHaveLength(1);
    expect(out[0].desc).toBe('Школа');
  });

  it('таблицу без шапки читает целиком', () => {
    expect(parseTabular('52.09;69.12;Школа\n52.10;69.13;ФАП')).toHaveLength(2);
  });
});

describe('что попадает в запись', () => {
  it('название берётся из своей колонки', () => {
    expect(parseTabular('52.09;69.12;Школа №3')[0].desc).toBe('Школа №3');
  });

  it('безымянной точке даётся номер, а не пустота', () => {
    expect(parseTabular('52.09;69.12')[0].desc).toBeTruthy();
  });

  it('район берётся из четвёртой колонки', () => {
    expect(parseTabular('52.09;69.12;Школа;Зерендинский')[0].district).toBe('Зерендинский');
  });

  it('без района подставляется заданный по умолчанию', () => {
    expect(parseTabular('52.09;69.12;Школа', 'Акмолинская')[0].district).toBe('Акмолинская');
  });

  it('у каждой точки свой номер', () => {
    const out = parseTabular('52.09;69.12;А\n52.10;69.13;Б\n52.11;69.14;В');
    expect(new Set(out.map((s) => s.id))).toHaveLength(3);
  });
});

/**
 * Границы Казахстана: точка за ними — это опечатка в координатах или
 * перепутанные местами широта с долготой. Молча положить её на карту
 * значит отправить бригаду в поле за тысячу километров.
 */
describe('что отбрасывается', () => {
  it('точка вне Казахстана', () => {
    expect(parseTabular('55.75;37.62;Москва')).toHaveLength(0);
  });

  it('широта с долготой, перепутанные местами', () => {
    // 69 широты — это Ямал, а не Акмолинская.
    expect(parseTabular('69.12;52.09;Школа')).toHaveLength(0);
  });

  it('строка без чисел', () => {
    expect(parseTabular('просто текст;ещё текст')).toHaveLength(0);
  });

  it('пустые строки между данными', () => {
    expect(parseTabular('52.09;69.12;А\n\n\n52.10;69.13;Б')).toHaveLength(2);
  });

  it('пустой файл — это ноль точек, а не ошибка', () => {
    expect(parseTabular('')).toEqual([]);
    expect(parseTabular('\n\n')).toEqual([]);
  });
});

describe('перевод строк', () => {
  it('файл из Windows читается так же, как из Linux', () => {
    expect(parseTabular('52.09;69.12;А\r\n52.10;69.13;Б')).toHaveLength(2);
  });
});

/**
 * Запятая в ячейке значит либо «дальше вторая координата», либо «дальше
 * дробная часть». Русский Excel пишет 52,091435 — и весь файл из
 * конторы импортировался нулём точек, молча.
 */
describe('запятая: дробная или разделитель', () => {
  it('файл русского Excel читается целиком', () => {
    const out = parseTabular(
      'Широта;Долгота;Название\n'
      + '52,091435;69,123456;Школа\n'
      + '52,095000;69,130000;ФАП\n'
      + '52,100000;69,140000;Аким аппарат',
    );
    expect(out).toHaveLength(3);
    expect(out[0].lat).toBeCloseTo(52.091435, 6);
    expect(out[2].desc).toBe('Аким аппарат');
  });

  it('пара в одной ячейке — с точками и с запятыми', () => {
    expect(parseTabular('52.09, 69.12\tШкола')[0].lat).toBeCloseTo(52.09, 6);
    expect(parseTabular('52,09 69,12\tШкола')[0].lat).toBeCloseTo(52.09, 6);
    expect(parseTabular('52,09; 69,12\tШкола')[0].lat).toBeCloseTo(52.09, 6);
    expect(parseTabular('52,09, 69,12\tШкола')[0].lon).toBeCloseTo(69.12, 6);
  });

  it('одно число парой не считается ни при каком написании', () => {
    // Иначе долгота берётся из дробной части и точка уезжает с карты.
    for (const one of ['52,091435', '52.091435', '52']) {
      expect(parseTabular(`${one};69,123456;Школа`)).toHaveLength(1);
      expect(parseTabular(`${one};69,123456;Школа`)[0].lon).toBeCloseTo(69.123456, 6);
    }
  });

  it('точка и запятая в одном файле не мешают друг другу', () => {
    const out = parseTabular('52.09;69.12;А\n52,10;69,13;Б');
    expect(out).toHaveLength(2);
    expect(out[1].lat).toBeCloseTo(52.10, 6);
  });
});
