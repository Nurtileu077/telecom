import { describe, it, expect } from 'vitest';
import { classifyEntity, cameraEntityKind, entityToCameraKind } from './KmlStructured';

/**
 * Чем является метка из файла.
 *
 * Это решение принимается один раз при импорте и дальше не
 * пересматривается: от него зависит, ляжет ли точка на карту муфтой,
 * камерой или узлом связи. Ошибка здесь не видна до тех пор, пока
 * кто-то не станет искать муфту и не найдёт её среди камер.
 *
 * Порядок правил важнее самих правил: «Перекресток» содержит корень,
 * по которому ловится муфта, «ЛУ» — корень линейного участка, «ОВН» —
 * опоры. Все три — камеры, и проверяться должны раньше.
 */

const kind = (name: string, folders: string[] = [], ext?: Record<string, string>) =>
  classifyEntity(folders, name, ext);

describe('что это за метка', () => {
  it('узел связи', () => {
    for (const n of ['OLT Кокшетау', 'ЦОД', 'АМС-1', 'Узел связи', 'magistral-1']) {
      expect(kind(n)).toBe('olt');
    }
  });

  it('транзитная муфта', () => {
    for (const n of ['МТОК-96', 'ОМСП', 'Транзитная муфта', 'TB-4']) {
      expect(kind(n)).toBe('tb');
    }
  });

  it('распределительный шкаф', () => {
    for (const n of ['ОРК-8', 'ОРКС', 'Бокс 16', 'NAP-3', 'Шкаф']) {
      expect(kind(n)).toBe('ork');
    }
  });

  it('муфта', () => {
    for (const n of ['Муфта №3', 'Joint', 'Сварная', 'splice-12']) {
      expect(kind(n)).toBe('joint');
    }
  });

  it('радиорелейка', () => {
    for (const n of ['РРЛ', 'Радиорелейная линия', 'Wireless link']) {
      expect(kind(n)).toBe('radio');
    }
  });

  it('камеры трёх видов', () => {
    expect(kind('Перекресток Абая — Ауэзова')).toBe('cam_intersect');
    expect(kind('ЛУ-7')).toBe('cam_lu');
    expect(kind('ОВН (с)')).toBe('cam_ovn');
  });
});

/**
 * Случаи, ради которых порядок правил и выстроен. Каждый из них —
 * настоящее название из файла заказчика, и каждый ловится не тем
 * правилом, если проверять в другом порядке.
 */
describe('корни слов, которые делят разные сущности', () => {
  it('«Перекресток» — камера, а не муфта', () => {
    expect(kind('Перекресток')).toBe('cam_intersect');
    expect(kind('Перекрёсток Абая')).toBe('cam_intersect');
  });

  it('«Линейный участок» — камера, а не муфта', () => {
    expect(kind('Линейный участок 4')).toBe('cam_lu');
  });

  it('«ОВН» — камера, а не опора', () => {
    expect(kind('ОВН')).toBe('cam_ovn');
    expect(kind('ОВН (с)')).toBe('cam_ovn');
  });

  it('«Транзитная муфта МТОК» — транзитная, а не простая', () => {
    expect(kind('Транзитная муфта МТОК-96')).toBe('tb');
  });

  it('радиорелейка побеждает всё: это не волокно вовсе', () => {
    expect(kind('РРЛ муфта ОРК перекресток')).toBe('radio');
  });
});

/**
 * Кириллица и границы слов. `\b` в регулярных выражениях с кириллицей не
 * работает вовсе — здесь это обошли соседями-небуквами, и проверить
 * обход надо именно на словах, внутри которых корень встречается.
 */
describe('корень внутри другого слова не считается', () => {
  it('«ЛУ» внутри слова камерой не делает', () => {
    expect(kind('Случай')).not.toBe('cam_lu');
    expect(kind('Аул Шалкар')).not.toBe('cam_lu');
  });

  /**
   * «Ровный» содержит «овн». Проверять напрямую нечем: незнакомая метка
   * и так становится камерой ОВН по умолчанию. Поэтому смотрим, побьёт
   * ли ложное совпадение настоящее правило рядом.
   */
  it('«овн» внутри слова не перебивает настоящее правило', () => {
    expect(kind('Ровный участок, муфта №3')).toBe('joint');
    expect(kind('Ровный участок, ОРК-8')).toBe('ork');
  });

  it('но отдельным словом — делает', () => {
    expect(kind('ЛУ')).toBe('cam_lu');
    expect(kind('точка ЛУ 3')).toBe('cam_lu');
  });

  it('разделители вокруг слова могут быть любыми', () => {
    for (const n of ['ЛУ-1', 'ЛУ_2', '(ЛУ)', 'ЛУ.', '№ ЛУ 4']) {
      expect(kind(n)).toBe('cam_lu');
    }
  });
});

describe('откуда берётся текст для решения', () => {
  it('имя папки участвует наравне с именем метки', () => {
    expect(kind('Точка 1', ['Муфты'])).toBe('joint');
    expect(kind('Точка 1', ['Проект', 'ОРК'])).toBe('ork');
  });

  it('и поля из ExtendedData тоже', () => {
    expect(kind('Точка 1', [], { тип: 'РРЛ' })).toBe('radio');
  });

  it('регистр не важен', () => {
    expect(kind('мУфТа')).toBe('joint');
    expect(kind('OLT')).toBe(kind('olt'));
  });
});

/**
 * Незнакомую метку не выбрасываем: лучше показать её на карте не тем
 * значком, чем потерять. Человек переназначит на месте.
 */
describe('незнакомое не теряется', () => {
  it('метка без узнаваемых слов всё равно попадает на карту', () => {
    expect(kind('Точка 17')).toBe('cam_ovn');
    expect(kind('')).toBe('cam_ovn');
  });
});

describe('вид камеры туда и обратно', () => {
  it('переводится без потерь', () => {
    for (const k of ['lu', 'intersection', 'ovn'] as const) {
      expect(entityToCameraKind(cameraEntityKind(k))).toBe(k);
    }
  });

  it('не-камера превращается в вид по умолчанию, а не в пустоту', () => {
    expect(entityToCameraKind('joint')).toBeTruthy();
    expect(entityToCameraKind('olt')).toBeTruthy();
  });
});

/**
 * Настоящие названия узлов и транзитных муфт из файлов заказчика.
 * Оба вида раньше опознавались неверно: «Узел связи» становился камерой,
 * «Транзитная муфта» — простой муфтой.
 */
describe('названия так, как их пишут в проекте', () => {
  it('узел связи во всех падежах', () => {
    for (const n of ['Узел связи', 'Узел связи Кокшетау', 'узла связи', 'Узел_связи']) {
      expect(kind(n)).toBe('olt');
    }
  });

  it('транзитная муфта во всех родах', () => {
    for (const n of [
      'Транзитная муфта', 'Транзитная муфта №4', 'транзитные муфты',
      'Транзитная-муфта', 'Транзитной муфты',
    ]) {
      expect(kind(n)).toBe('tb');
    }
  });

  it('простая муфта транзитной не становится', () => {
    for (const n of ['Муфта №3', 'Муфта прямая', 'Оптическая муфта']) {
      expect(kind(n)).toBe('joint');
    }
  });

  it('«транзит» без муфты муфтой не делает', () => {
    expect(kind('Транзитный участок')).not.toBe('tb');
  });
});
