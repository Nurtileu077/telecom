function norm(s: string): string {
  return s.toLowerCase().replace(/ё/g, 'е').trim();
}

const INDEX = new Map<string, Term>();
for (const t of GLOSSARY) {
  INDEX.set(norm(t.term), t);
  for (const a of t.aka ?? []) if (!INDEX.has(norm(a))) INDEX.set(norm(a), t);
}

/** Что это за слово. Пусто — значит в словаре его нет, и выдумывать нечего. */
export function lookup(word: string): Term | null {
  return INDEX.get(norm(word)) ?? null;
}

/** Поиск по словарю — для справки, а не для подсказки под курсором. */
export function searchGlossary(query: string): Term[] {
  const q = norm(query);
  if (!q) return GLOSSARY;
  return GLOSSARY.filter((t) => norm(t.term).includes(q)
    || norm(t.short).includes(q)
    || (t.aka ?? []).some((a) => norm(a).includes(q)));
}

/**
 * Слова словаря, встретившиеся в тексте.
 *
 * Нужно, чтобы подсветить их в примечании или в названии участка, а не
 * заставлять человека искать объяснение самому.
 */
export function termsIn(text: string): Term[] {
  const words = norm(text).split(/[^0-9a-zа-я-]+/).filter(Boolean);
  const seen = new Set<string>();
  const out: Term[] = [];
  for (const w of words) {
    const t = INDEX.get(w);
    if (!t || seen.has(t.term)) continue;
    seen.add(t.term);
    out.push(t);
  }
  return out;
}
